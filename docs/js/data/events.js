/**
 * Flatten the by-location map into the flat pool the event manager consumes,
 * stamping `requiredLocation` from the declaring key.
 *
 * Returns fresh objects every call so a caller can safely mutate the result —
 * the `{friend}` substitution bug in the original depended on it not doing so.
 */
export function buildEventPool() {
  const pool = [];
  for (const [locationId, events] of Object.entries(EVENTS_BY_LOCATION)) {
    for (const event of events) {
      pool.push({ ...event, requiredLocation: locationId });
    }
  }
  return pool;
}

/** Every event owned by one character, in catalogue order. */
export function eventsForCharacter(characterId) {
  return buildEventPool().filter((e) => e.character === characterId);
}

/** Every event that can fire at one location. */
export function eventsAtLocation(locationId) {
  return buildEventPool().filter((e) => e.requiredLocation === locationId);
}

/** characterId → number of events, for balance tests and tooling. */
export function eventCountsByCharacter() {
  const counts = new Map();
  for (const e of buildEventPool()) {
    counts.set(e.character, (counts.get(e.character) ?? 0) + 1);
  }
  return counts;
}
