/**
 * Event catalogue.
 *
 * ## The one rule
 *
 * **Every event belongs to exactly one character, and fires at exactly one
 * location — the location that character is bound to in `characters.js`.**
 *
 * That is why the pool is declared as a map of location id → events rather
 * than as a flat list: the location gate is structural, not a field somebody
 * has to remember to fill in, so an event can never drift away from the
 * person it belongs to. `buildEventPool()` flattens the map and stamps
 * `requiredLocation` on the way out.
 *
 * Every character in the cast has **at least three** events. That floor is
 * enforced by test, and it is what makes a location feel like somewhere
 * specific people are rather than a slot machine with scenery.
 *
 * A handful of events carry an extra gate on top — `requiredWeather`, a
 * `minimumDay`, or the burnout counter — but those are always *additional*
 * to the location, never instead of it.
 */

