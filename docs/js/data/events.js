export const Rarity = Object.freeze({
  STANDARD: 'standard',
  RARE_HELPFUL: 'rare_helpful',
  RARE_HURTFUL: 'rare_hurtful',
});

export const WEIGHT_STANDARD = 10.0;
export const WEIGHT_RARE_HELPFUL = 2.0;
export const WEIGHT_RARE_HURTFUL = 2.0;

/** Weight is a pure function of rarity — 10 for common, 2 for either rare. */
export function weightForRarity(rarity) {
  if (rarity === Rarity.RARE_HELPFUL) return WEIGHT_RARE_HELPFUL;
  if (rarity === Rarity.RARE_HURTFUL) return WEIGHT_RARE_HURTFUL;
  return WEIGHT_STANDARD;
}

/** Human-readable rarity label (EventDefinition.rarity_name). */
export function rarityName(rarity) {
  switch (rarity) {
    case Rarity.STANDARD:
      return 'Common';
    case Rarity.RARE_HELPFUL:
      return 'Rare (Helpful)';
    case Rarity.RARE_HURTFUL:
      return 'Rare (Hurtful)';
    default:
      return '';
  }
}

/**
 * One event, minus its location — the location comes from the key it is
 * declared under, so it cannot be mistyped or left behind after a move.
 *
 * @param {string} id        unique slug
 * @param {string} character owner; must be bound to the declaring location
 * @param {string} title     shown on the result card
 * @param {string} description
 * @param {string} category
 * @param {string} rarity
 * @param {{sanity?:number, money?:number, energy?:number,
 *          reputation?:number, insight?:number}} [deltas]
 * @param {object} [extra]   additional gates: minimumDay, requiredWeather, …
 */
function ev(id, character, title, description, category, rarity, deltas = {}, extra = {}) {
  return {
    id,
    title,
    description,
    category,
    rarity,
    character,
    sanityDelta: deltas.sanity ?? 0,
    moneyDelta: deltas.money ?? 0,
    energyDelta: deltas.energy ?? 0,
    reputationDelta: deltas.reputation ?? 0,
    insightDelta: deltas.insight ?? 0,
    weight: weightForRarity(rarity),
    /** Filled in by buildEventPool() from the declaring key. */
    requiredLocation: '',
    minimumDay: 1,
    allowedWeekdays: [],
    /** Retained for compatibility; the location gate is the primary one. */
    requiredTag: '',
    /** Optional extra gate on the day's weather id. */
    requiredWeather: '',
    ...extra,
  };
}

